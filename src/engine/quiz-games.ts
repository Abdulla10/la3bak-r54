const pickUnused = <T extends { key: string }>(items: T[], used: string[], rng: Rng): T => {
  const pool = items.filter((i) => !used.includes(i.key));
  const from = pool.length ? pool : items;
  return from[Math.floor(rng() * from.length)];
};

/** يبني سؤالاً من جواب صحيح وثلاث إجابات خاطئة، بترتيب عشوائي */
function build(rng: Rng, key: string, prompt: string, correct: string, wrong: string[], big?: string): Question {
  const options = shuffle([correct, ...shuffle(wrong, rng).slice(0, 3)], rng);
  return { key, prompt, big, options, answer: options.indexOf(correct) };
}


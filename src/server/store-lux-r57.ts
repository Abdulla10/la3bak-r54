/** R57: أيديات حساب مميزة. كل رقم ينباع مرة وحدة لحساب واحد، ويصير هو رقمك الظاهر (displayPlayerId).
 * السعر حسب ندرة النمط. الأرقام المستخدمة من حسابات ثانية ما تنعرض ولا تنباع. */
const SID = (n: string, price: number, rarity: Rarity): ShopItem => ({ id: `sid-${n}`, slot: 'special-id', name: `أيدي ${n}`, icon: '🆔', price, currency: 'gems', desc: `رقم حساب مميز يظهر بملفك وبالغرف بدل رقمك العادي: ${n}`, css: n, permanent: true, rarity, set: 'lux' });
/** R58m (طلب المالك): أسعار متنوعة حسب نمط الرقم — المكرر 45 مليون، التسلسل 40، المتناوب 35، الدائري 30، المرآة 25، الأزواج والسنوات 20.
 * كل ما قصر الرقم غلي (6 أرقام ×1.6، 5 ×2.5، 4 ×5، 3 ×8). الأيديات القديمة كلها باقية (ما ينحذف شي)، والسعر الجديد للشراء الجديد فقط. */
export function idPattern(n: string): 'repeat' | 'sequence' | 'alternate' | 'round' | 'mirror' | 'pairs' {
  if (/^(\d)\1+$/.test(n)) return 'repeat';
  const d = [...n].map(Number); const step = d.slice(1).every((x, i) => x - d[i] === 1) || d.slice(1).every((x, i) => x - d[i] === -1);
  if (step) return 'sequence';
  if (n.length >= 4 && /^(\d)(\d)(?:\1\2)*\1?$/.test(n) && n[0] !== n[1]) return 'alternate';
  if (/^[1-9]0+$/.test(n)) return 'round';
  if (n.length >= 5 && n === [...n].reverse().join('')) return 'mirror';
  return 'pairs';
}
